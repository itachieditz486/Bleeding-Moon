#!/usr/bin/env python3
"""Writes sw.js with a precache list of every runtime file and a content-hash cache name (so updates invalidate old caches)."""
import hashlib, os, json
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
files = ['./', 'index.html', 'manifest.webmanifest', 'icons/icon-192.png', 'icons/icon-512.png']
for base, _, fs in os.walk(os.path.join(ROOT, 'src')): files += [os.path.relpath(os.path.join(base, f), ROOT) for f in fs if f.endswith('.js')]
for base, _, fs in os.walk(os.path.join(ROOT, 'assets', 'audio')):
    if 'licenses' in base: continue
    files += [os.path.relpath(os.path.join(base, f), ROOT) for f in fs if f.endswith(('.ogg', '.json'))]
files = sorted(set(files))
h = hashlib.sha256()
for f in files:
    if f != './': h.update(open(os.path.join(ROOT, f), 'rb').read())
ver = h.hexdigest()[:10]
open(os.path.join(ROOT, 'sw.js'), 'w').write(f"""// Generated by tools/gen_sw.py - do not edit. Cache-first offline support.
const CACHE = 'bleeding-moon-{ver}';
const FILES = {json.dumps(files)};
self.addEventListener('install', e => e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())));
self.addEventListener('activate', e => e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener('fetch', e => {{
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then(r => r || fetch(e.request).then(res => {{ const copy = res.clone(); if (res.ok) caches.open(CACHE).then(c => c.put(e.request, copy)); return res; }}).catch(() => caches.match('index.html'))));
}});
""")
print('sw.js:', len(files), 'files, cache', ver)
